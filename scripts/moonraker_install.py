"""Transactional Moonraker extension installer."""
from pathlib import Path
import pathlib
import subprocess
from moonraker_candidates import prepare_config, prepare_module
from moonraker_service_guard import guard, api

CONFIG = Path("/usr/share/moonraker/moonraker.conf")
MODULE = Path("/usr/share/moonraker-env/lib/python3.9/site-packages/preprocess_cancellation.py")
ROOT = Path("/mnt/UDISK/helper-backups")

def preflight():
    guard()
    if api("/server/info")["warnings"]:
        raise RuntimeError("Moonraker warnings; resolve before installation")
    if list(ROOT.glob("moonraker-*/PENDING")):
        raise RuntimeError("Pending recovery journal; resolve before installation")
    changes = [(MODULE, prepare_module(MODULE.read_bytes())),
               (CONFIG, prepare_config(CONFIG.read_bytes()))]
    required = {"EXCLUDE_OBJECT_DEFINE", "EXCLUDE_OBJECT_START", "EXCLUDE_OBJECT_END"}
    if not required.issubset(api("/printer/gcode/help")):
        raise RuntimeError("Klipper object commands missing")
    return changes

def adoption_test():
    changes = preflight()
    if any(p.read_bytes() != data for p, data in changes):
        raise RuntimeError("Fresh activation not yet enabled")
    if api("/server/config")["config"]["file_manager"]["enable_object_processing"] is not True:
        raise RuntimeError("Effective object processing disabled")
    print("PASS: Existing correction verified")
    print("PASS: No pending recovery journals")
    print("PASS: No file replacement or restart required")



def functional_verify():
    import tempfile, os
    def require(ok, message):
        if not ok:
            raise RuntimeError(message)
        print("PASS: "+message)
    required={"EXCLUDE_OBJECT_DEFINE","EXCLUDE_OBJECT_START","EXCLUDE_OBJECT_END"}
    require(required.issubset(api("/printer/gcode/help")), "Klipper object commands")
    with tempfile.TemporaryDirectory() as d:
        f=pathlib.Path(d)/"test.gcode"
        f.write_text("; generated by PrusaSlicer 2.8.0 on 2026-11-24 at 23:05:00 UTC\n;LAYER_CHANGE\n;Z:0.2\n; printing object TestCube id:0 copy 0\n; test\n; stop printing object TestCube id:0 copy 0\n")
        env=os.environ.copy()
        env.pop("PYTHONPATH",None)
        env["PYTHONDONTWRITEBYTECODE"]="1"
        result = subprocess.run(["/usr/share/moonraker-env/bin/python","/usr/share/moonraker/components/file_manager/metadata.py","-p",d,"-f",f.name,"--check-objects"],check=False,timeout=60,env=env,cwd=d,stdout=subprocess.PIPE,stderr=subprocess.PIPE)
        if result.returncode:
            print(result.stdout.decode(errors="replace"))
            print(result.stderr.decode(errors="replace"))
            result.check_returncode()
        commands={line.split()[0] for line in f.read_text().splitlines() if line.strip() and not line.startswith(";")}
        require(required.issubset(commands) and not commands.intersection({"DEFINE_OBJECT","START_CURRENT_OBJECT","END_CURRENT_OBJECT"}),"Functional metadata processing")
    

def install():
    import fcntl
    from moonraker_ownership import register, load
    from moonraker_removal import restoration_plan
    from moonraker_activation import activate
    from moonraker_service_recovery import recover_service
    from moonraker_service_guard import SERVICE
    ROOT.mkdir(parents=True, exist_ok=True)
    with (ROOT / ".moonraker.lock").open("a") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        changes = preflight()
        ownership = ROOT / "moonraker-ownership.json"
        if ownership.exists():
            record, owned_journal = load(ROOT)
            if owned_journal is not None:
                restoration_plan(owned_journal, [CONFIG, MODULE])
            if any(p.read_bytes() != data for p, data in changes):
                raise RuntimeError("Registered installation changed; manual review required")
        elif list(ROOT.glob("moonraker-*/COMMITTED")):
            raise RuntimeError("Unclassified committed journal; manual review required")
        if all(p.read_bytes() == data for p, data in changes):
            adoption_test()
            functional_verify()
            if not ownership.exists():
                register(ROOT)
            kind = load(ROOT)[0]["kind"]
            print("PASS: Persistent ownership:", kind)
            if kind == "adopted":
                print("Existing corrections remain user-owned; removal must not revert them")
            return
        baseline = api("/server/config")["config"]["file_manager"]["enable_object_processing"]
        service = SERVICE.read_bytes()
        def verify():
            guard()
            if api("/server/info")["warnings"]:
                raise RuntimeError("Moonraker warnings")
            if api("/server/config")["config"]["file_manager"]["enable_object_processing"] is not True:
                raise RuntimeError("Object processing disabled")
            for path, candidate in changes:
                if path.read_bytes() != candidate:
                    raise RuntimeError("Candidate mismatch")
            functional_verify()
        journal = activate(ROOT, changes, guard,
                           lambda: recover_service(True, service),
                           verify,
                           lambda: recover_service(baseline, service))
        register(ROOT, journal, baseline)
        print("PASS: Activation committed:", journal)

if __name__ == "__main__":
    install()
