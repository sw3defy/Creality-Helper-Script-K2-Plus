#!/bin/sh
# Maintenance validation only; no firmware or configuration changes.
SCRIPT_DIR=/mnt/UDISK/helper-script
. "$SCRIPT_DIR/scripts/system.sh"
case "$1" in
install)
python3 - <<'PY'
import json, urllib.request, pathlib, hashlib, subprocess, tempfile, os
def api(path):
    with urllib.request.urlopen("http://127.0.0.1:7125"+path, timeout=10) as r:
        return json.load(r)["result"]
def require(ok, message):
    if not ok:
        raise SystemExit("FAIL: "+message)
    print("PASS: "+message)
info=api("/server/info")
require(info["klippy_connected"] and info["klippy_state"]=="ready" and not info["warnings"] and not info["failed_components"],"Moonraker and Klipper healthy")
require("update_manager" not in info["components"],"Native update manager disabled")
require(api("/printer/objects/query?print_stats")["status"]["print_stats"]["state"] in ("standby","complete","cancelled"),"Printer idle")
require(not api("/server/job_queue/status").get("queued_jobs"),"Queue empty")
require(api("/server/config")["config"]["file_manager"]["enable_object_processing"] is True,"Object processing enabled")
p=pathlib.Path("/usr/share/moonraker-env/lib/python3.9/site-packages/preprocess_cancellation.py")
require(hashlib.sha256(p.read_bytes()).hexdigest()=="ef07606aafc7d2188cda29a207d4950cd582fa56679c6eec666e616450dab4e4","Verified corrected preprocessor")
required={"EXCLUDE_OBJECT_DEFINE","EXCLUDE_OBJECT_START","EXCLUDE_OBJECT_END"}
require(required.issubset(api("/printer/gcode/help")),"Klipper object commands")
with tempfile.TemporaryDirectory() as d:
    f=pathlib.Path(d)/"test.gcode"
    f.write_text("; generated by PrusaSlicer 2.8.0 on 2026-11-24 at 23:05:00 UTC\n;LAYER_CHANGE\n;Z:0.2\n; printing object TestCube id:0 copy 0\n; test\n; stop printing object TestCube id:0 copy 0\n")
    env=os.environ.copy()
    env.pop("PYTHONPATH",None)
    env["PYTHONDONTWRITEBYTECODE"]="1"
    subprocess.run(["/usr/share/moonraker-env/bin/python","/usr/share/moonraker/components/file_manager/metadata.py","-p",d,"-f",f.name,"--check-objects"],check=True,timeout=60,env=env,cwd=d)
    commands={line.split()[0] for line in f.read_text().splitlines() if line.strip() and not line.startswith(";")}
    require(required.issubset(commands) and not commands.intersection({"DEFINE_OBJECT","START_CURRENT_OBJECT","END_CURRENT_OBJECT"}),"Functional metadata processing")
print("Existing corrected installation verified. No restart or changes required.")
PY
status=$?
[ "$status" -eq 0 ] || { log_error "Validation failed. Fresh installation remains blocked."; exit "$status"; }
log_success "Maintenance validation passed. Safe Update Manager is not yet installed."
;;
remove) log_error "Removal remains blocked pending ownership and rollback validation."; exit 1 ;;
*) exit 2 ;;
esac
